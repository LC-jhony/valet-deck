// Package php manages parallel PHP installations under php/<minor>/.
// Each version keeps its own php.ini (created once, preserved on upgrades),
// its own php.ini scan dirs and its own FPM unix socket in run/.
package php

import (
	"bufio"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/lair-sh/lair/internal/app"
	"github.com/lair-sh/lair/internal/version"
)

// Info describes an installed PHP minor line.
type Info struct {
	Version string `json:"version"`
	Build   string `json:"build"`
	Minor   string `json:"minor"`
	Dir     string `json:"-"`
}

// Marker is written as lair.json in each version directory. Legacy flock.json
// files are still read, so upgrades never hide an already installed version.
type Marker struct {
	Version string `json:"version"`
	Build   string `json:"build"`
	Minor   string `json:"minor"`
}

// Installed lists installed PHP versions, newest first.
func Installed(paths app.Paths) ([]Info, error) {
	entries, err := os.ReadDir(paths.PHP)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	out := []Info{}
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		data, err := readMarker(filepath.Join(paths.PHP, e.Name()))
		if err != nil {
			continue
		}
		var m Marker
		if err := json.Unmarshal(data, &m); err != nil {
			continue
		}
		m.Minor = e.Name()
		out = append(out, Info{Version: m.Version, Build: m.Build, Minor: m.Minor, Dir: filepath.Join(paths.PHP, e.Name())})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Minor > out[j].Minor })
	return out, nil
}

// WriteMarker writes lair.json for a newly installed version.
func WriteMarker(info Info) error {
	data, err := json.MarshalIndent(Marker{Version: info.Version, Build: info.Build, Minor: info.Minor}, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(info.Dir, "lair.json"), data, 0o644)
}

// readMarker prefers the canonical lair.json but falls back to the legacy
// flock.json marker written by older builds.
func readMarker(dir string) ([]byte, error) {
	data, err := os.ReadFile(filepath.Join(dir, "lair.json"))
	if err == nil {
		return data, nil
	}
	if !os.IsNotExist(err) {
		return nil, err
	}
	return os.ReadFile(filepath.Join(dir, "flock.json"))
}

// defaultINI is a development-oriented php.ini. It is created once per
// version and never overwritten by an upgrade.
const defaultINI = `; Generated by Lair. Safe to edit; upgrades preserve this file.
memory_limit = 512M
upload_max_filesize = 128M
post_max_size = 128M
max_execution_time = 120
display_errors = On
display_startup_errors = On
error_reporting = E_ALL
log_errors = On
date.timezone = UTC

; Local CA bundle so https://*.test works from PHP.
openssl.cafile = {CAFILE}

; Opcache for development: enabled, no timestamp validation issues in tests.
opcache.enable = 1
opcache.enable_cli = 1
opcache.validate_timestamps = 1
opcache.revalidate_freq = 0

; Laravel-typical extensions.
extension = bcmath
extension = curl
extension = gd
extension = intl
extension = mbstring
extension = pdo_mysql
extension = pdo_pgsql
extension = pdo_sqlite
extension = zip
`

// EnsureINI creates the version's php.ini once. It returns the path.
func EnsureINI(info Info, caFile string) (string, error) {
	path := filepath.Join(info.Dir, "php.ini")
	if _, err := os.Stat(path); err == nil {
		return path, nil
	} else if !os.IsNotExist(err) {
		return "", err
	}
	body := strings.ReplaceAll(defaultINI, "{CAFILE}", caFile)
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		return "", err
	}
	// CLI-only scan dir: pcov here, never in FPM.
	cliDir := filepath.Join(info.Dir, "conf.d-cli")
	if err := os.MkdirAll(cliDir, 0o755); err != nil {
		return "", err
	}
	if err := os.WriteFile(filepath.Join(cliDir, "30-pcov.ini"), []byte("zend_extension=pcov\nbootstrap=pcov.enabled=0\n"), 0o644); err != nil {
		return "", err
	}
	// Xdebug is present but disabled by default; a separate FPM pool can opt in.
	xdebugDir := filepath.Join(info.Dir, "conf.d-xdebug")
	if err := os.MkdirAll(xdebugDir, 0o755); err != nil {
		return "", err
	}
	if err := os.WriteFile(filepath.Join(xdebugDir, "20-xdebug.ini"), []byte("zend_extension=xdebug\n"), 0o644); err != nil {
		return "", err
	}
	return path, nil
}

// ResolveVersion picks a PHP minor line for a project. Precedence:
//
//	isolated > .lairrc (php=) > legacy .flockrc > default > newest installed
//
// The returned value is a minor line such as "8.4"; callers map it to an
// installed version directory.
func ResolveVersion(projectDir, isolated, defaultVersion string, available []string) (string, error) {
	if isolated != "" {
		return matchLine(isolated, available)
	}
	// .lairrc is canonical; .flockrc is still read for existing projects.
	for _, name := range []string{".lairrc", ".flockrc"} {
		if v := fromRCFile(filepath.Join(projectDir, name)); v != "" {
			return matchLine(v, available)
		}
	}
	if defaultVersion != "" {
		return matchLine(defaultVersion, available)
	}
	if len(available) == 0 {
		return "", fmt.Errorf("no PHP versions installed")
	}
	sort.Sort(byMinor(available))
	return available[len(available)-1], nil
}

func matchLine(request string, available []string) (string, error) {
	// Accept either a minor line (8.4) or a full version (8.4.3).
	line := request
	if parsed, err := version.Parse(request); err == nil {
		line = parsed.MinorLine()
	}
	for _, a := range available {
		if a == line || strings.HasPrefix(a, line+".") {
			return a, nil
		}
	}
	return "", fmt.Errorf("PHP %s is not installed", request)
}

func fromRCFile(path string) string {
	f, err := os.Open(path)
	if err != nil {
		return ""
	}
	defer f.Close()
	scanner := bufio.NewScanner(f)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if strings.HasPrefix(line, "php=") || strings.HasPrefix(line, "php:") {
			return strings.TrimSpace(line[strings.IndexAny(line, "=:"):][1:])
		}
	}
	return ""
}

type byMinor []string

func (s byMinor) Len() int      { return len(s) }
func (s byMinor) Swap(i, j int) { s[i], s[j] = s[j], s[i] }
func (s byMinor) Less(i, j int) bool {
	ai, errA := version.Parse(s[i])
	bi, errB := version.Parse(s[j])
	if errA != nil || errB != nil {
		return s[i] < s[j]
	}
	return ai.Compare(bi) < 0
}

// Env returns the environment that makes the shim use this exact PHP version
// with its own ini, CA bundle and CLI scan dir.
func Env(info Info, paths app.Paths) []string {
	cliDir := filepath.Join(info.Dir, "conf.d-cli")
	mainINI := filepath.Join(info.Dir, "php.ini")
	caFile := filepath.Join(paths.Certs, "ca.pem")
	return []string{
		"PHPRC=" + mainINI,
		"PHP_INI_SCAN_DIR=" + cliDir,
		"SSL_CERT_FILE=" + caFile,
		"CURL_CA_BUNDLE=" + caFile,
	}
}

// FPMConfig renders a pool configuration for a site. Each site gets its own
// unix socket under run/; the debug pool is separate and opt-in.
func FPMConfig(paths app.Paths, info Info, site string, debug bool) (string, error) {
	if site == "" || strings.ContainsAny(site, `/\`) {
		return "", fmt.Errorf("invalid site name %q", site)
	}
	sock, err := paths.SocketPath("fpm-" + site)
	if err != nil {
		return "", err
	}
	pool := "lair-" + site
	if debug {
		pool += "-xdebug"
		sock, err = paths.SocketPath("fpm-" + site + "-dbg")
		if err != nil {
			return "", err
		}
	}
	scanDir := filepath.Join(info.Dir, "conf.d-cli")
	if debug {
		scanDir = filepath.Join(info.Dir, "conf.d-xdebug")
	}
	return fmt.Sprintf(`[%s]
user = %%u
group = %%g
listen = %s
listen.owner = %%u
listen.group = %%g
listen.mode = 0600
pm = ondemand
pm.max_children = 8
pm.process_idle_timeout = 10s
php_value[display_errors] = %s
php_admin_value[error_log] = %s
php_admin_value[date.timezone] = UTC
; scan dir is injected via env by the supervisor: %s
`, pool, sock, boolOn(debug), filepath.Join(paths.Log, site+"-php.log"), scanDir), nil
}

func boolOn(b bool) string {
	if b {
		return "On"
	}
	return "Off"
}

// RequiredExtensions inspects a project's composer.json and .env for
// extension requirements and reports which ones are not enabled in the given
// php.ini. This is advisory: it never edits project files.
func RequiredExtensions(projectDir, iniPath string) ([]string, []string, error) {
	seen := map[string]bool{}

	// composer.json: "ext-*" requirements.
	if data, err := os.ReadFile(filepath.Join(projectDir, "composer.json")); err == nil {
		var doc struct {
			Require map[string]string `json:"require"`
		}
		if json.Unmarshal(data, &doc) == nil {
			for name := range doc.Require {
				if strings.HasPrefix(name, "ext-") {
					seen[strings.TrimPrefix(name, "ext-")] = true
				}
			}
		}
	}
	// .env: DB_CONNECTION and CACHE_DRIVER hints.
	if data, err := os.ReadFile(filepath.Join(projectDir, ".env")); err == nil {
		env := string(data)
		if strings.Contains(env, "DB_CONNECTION=pgsql") || strings.Contains(env, "DB_CONNECTION=") && strings.Contains(env, "pgsql") {
			seen["pdo_pgsql"] = true
		}
		if strings.Contains(env, "CACHE_DRIVER=redis") || strings.Contains(env, "SESSION_DRIVER=redis") {
			seen["redis"] = true
		}
	}
	required := make([]string, 0, len(seen))
	for e := range seen {
		required = append(required, e)
	}
	sort.Strings(required)

	enabled := map[string]bool{}
	if data, err := os.ReadFile(iniPath); err == nil {
		for _, line := range strings.Split(string(data), "\n") {
			line = strings.TrimSpace(line)
			if strings.HasPrefix(line, "extension=") {
				enabled[strings.TrimSpace(strings.TrimPrefix(line, "extension="))] = true
			}
			if strings.HasPrefix(line, "zend_extension=") {
				enabled[strings.TrimSpace(strings.TrimPrefix(line, "zend_extension="))] = true
			}
		}
	}
	missing := []string{}
	for _, e := range required {
		if !enabled[e] {
			missing = append(missing, e)
		}
	}
	return required, missing, nil
}
