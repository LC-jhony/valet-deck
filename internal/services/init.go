package services

import (
	"fmt"
	"os"
	"path/filepath"

	"github.com/lair-sh/lair/internal/app"
)

// InitNeeded reports whether first-run data initialisation is required.
func InitNeeded(id, dataDir string) bool {
	switch id {
	case "postgres":
		_, err := os.Stat(filepath.Join(dataDir, "PG_VERSION"))
		return os.IsNotExist(err)
	case "mysql", "mariadb":
		entries, err := os.ReadDir(dataDir)
		return os.IsNotExist(err) || err == nil && len(entries) == 0
	default:
		_, err := os.Stat(dataDir)
		return os.IsNotExist(err)
	}
}

// InitCommand returns the argv for first-run data initialisation. The command
// runs with the service's install directory as working directory where needed.
func InitCommand(paths app.Paths, id, version, build string) (argv []string, workDir string, err error) {
	install := InstallDir(paths, id, version, build)
	data := DataPath(paths, id, version)
	switch id {
	case "postgres":
		return []string{
			filepath.Join(install, "bin", "initdb"),
			"-D", data,
			"-U", "postgres",
			"--auth=trust",
			"-E", "UTF8",
			"--locale=C",
		}, install, nil
	case "mysql":
		return []string{
			filepath.Join(install, "bin", "mysqld"),
			"--no-defaults",
			"--initialize-insecure",
			"--basedir=" + install,
			"--datadir=" + data,
		}, install, nil
	case "mariadb":
		// MariaDB's script must run from the installation directory with a
		// relative --basedir.
		return []string{
			filepath.Join(install, "scripts", "mariadb-install-db"),
			"--no-defaults",
			"--basedir=.",
			"--datadir=" + data,
			"--auth-root-authentication-method=normal",
			"--skip-test-db",
		}, install, nil
	case "mongodb", "redis", "valkey", "meilisearch", "typesense", "rustfs":
		return nil, install, nil // data dir creation is enough
	default:
		return nil, "", fmt.Errorf("unknown service %q", id)
	}
}

// EnsureDataDir creates the data directory and, for MySQL-family services,
// writes a commented my.cnf exactly once. It is never overwritten on upgrade.
func EnsureDataDir(paths app.Paths, id, dataDir string) error {
	if err := os.MkdirAll(dataDir, 0o700); err != nil {
		return err
	}
	if id != "mysql" && id != "mariadb" {
		return nil
	}
	path := filepath.Join(dataDir, "my.cnf")
	if _, err := os.Stat(path); err == nil {
		return nil
	} else if !os.IsNotExist(err) {
		return err
	}
	body := fmt.Sprintf(`# Generated by Lair on first install. Edit freely; never overwritten.
# Port, bind address, socket, datadir and basedir are managed by Lair and must
# not be set here (use --port when installing).
[mysqld]
character-set-server = utf8mb4
collation-server = utf8mb4_unicode_ci
default-authentication-plugin = mysql_native_password
# innodb_buffer_pool_size = 256M
`)
	return os.WriteFile(path, []byte(body), 0o600)
}
